static void test_library_rank()
{
    BEGIN_TEST ("library_rank");
    SKIP_IF_NO_DEMO();

    DnaExtractor ex;
    DnaLibrary lib;
    lib.scanAndAnalyze (ex);
    const juce::StringArray noBoost;

    // Self-similarity: an entry's own DNA ranks it first at exactly 100%.
    const auto dbg = lib.getDebugSnapshot();
    const auto* bass = findDebug (dbg, "deep bass loop");
    CHECK (bass != nullptr);
    lib.rankAgainst (bass->dna, 1.0f, 1.0f, 1.0f, noBoost, 1.0f);
    {
        const auto snap = lib.getSnapshot();
        CHECK (snap.size() == 9);
        CHECK (snap[0].name == "deep bass loop");
        CHECK (snap[0].scorePct == 100.0f);
        for (size_t i = 1; i < snap.size(); ++i)
            CHECK (snap[i - 1].scorePct >= snap[i].scorePct); // sorted desc
    }

    // Near-duplicate: a fresh 55 Hz sine surfaces the LOW-dominant loops.
    // (deep-bass-loop and full-mix-loop are both low-leaning and score
    // within a hair of each other at 3-macro-band resolution — the ranking
    // is genuinely ambiguous there, so assert the meaningful property.)
    DnaFingerprint q55;
    const auto b55 = makeSine (55.0f, 0.5f, 44100.0, 4.0);
    CHECK (ex.extractDna (b55.data(), (int) b55.size(), 44100.0, q55));
    lib.rankAgainst (q55, 1.0f, 1.0f, 1.0f, noBoost, 1.0f);
    {
        const auto snap = lib.getSnapshot();
        for (size_t i = 0; i < 5 && i < snap.size(); ++i)
            std::printf ("    rank %zu: %s (%.3f%%)\n",
                         i + 1, snap[i].name.toRawUTF8(), snap[i].scorePct);
        CHECK (snap[0].scorePct > 90.0f);
        bool bassInTop3 = false;
        for (size_t i = 0; i < 3 && i < snap.size(); ++i)
            if (snap[i].name == "deep bass loop")
                bassInTop3 = true;
        CHECK (bassInTop3);
    }

    // Band weights steer the ranking: low-weighted vs high-weighted orders differ.
    lib.rankAgainst (q55, 1.0f, 0.0f, 0.0f, noBoost, 1.0f);
    const auto lowW = lib.getSnapshot();
    lib.rankAgainst (q55, 0.0f, 0.0f, 1.0f, noBoost, 1.0f);
    const auto highW = lib.getSnapshot();
    bool orderDiffers = false;
    for (size_t i = 0; i < lowW.size(); ++i)
        if (lowW[i].name != highW[i].name)
            orderDiffers = true;
    CHECK (orderDiffers);

    // All-zero weights fall back to equal weights (Daedalus guard), bit-identical.
    lib.rankAgainst (q55, 0.0f, 0.0f, 0.0f, noBoost, 1.0f);
    const auto zeroW = lib.getSnapshot();
    lib.rankAgainst (q55, 1.0f, 1.0f, 1.0f, noBoost, 1.0f);
    const auto eqW = lib.getSnapshot();
    for (size_t i = 0; i < zeroW.size(); ++i)
    {
        CHECK (zeroW[i].name == eqW[i].name);
        CHECK (zeroW[i].scorePct == eqW[i].scorePct);
    }

    // Empty boost list: the boost factor must not matter (v2.3 bit-identical).
    lib.rankAgainst (q55, 1.0f, 1.0f, 1.0f, noBoost, 2.0f);
    const auto bf2 = lib.getSnapshot();
    for (size_t i = 0; i < bf2.size(); ++i)
        CHECK (bf2[i].scorePct == eqW[i].scorePct);
}

static void test_library_boost()
{
    BEGIN_TEST ("library_boost");
    SKIP_IF_NO_DEMO();

    DnaExtractor ex;
    DnaLibrary lib;
    lib.scanAndAnalyze (ex);
    const auto dbg = lib.getDebugSnapshot();
    const auto* bass = findDebug (dbg, "deep bass loop");
    CHECK (bass != nullptr);

    const juce::StringArray noBoost;
    lib.rankAgainst (bass->dna, 1.0f, 1.0f, 1.0f, noBoost, 1.0f);
    const auto plain = lib.getSnapshot();

    // Energy-role boost: multiplicative, capped at 100, never a filter.
    juce::StringArray hats;
    hats.add ("hats");
    lib.rankAgainst (bass->dna, 1.0f, 1.0f, 1.0f, hats, 2.0f);
    {
        const auto snap = lib.getSnapshot();
        CHECK (snap.size() == 9); // nothing hidden: a boost, never a filter
        for (const auto& e : snap)
        {
            const auto* d = findDebug (dbg, e.name.toRawUTF8());
            const auto* p = findEntry (plain, e.name.toRawUTF8());
            CHECK (d != nullptr && p != nullptr);
            if (d == nullptr || p == nullptr)
                continue;
            const bool shouldBoost = (d->role == "hats");
            CHECK (e.boosted == shouldBoost);
            if (shouldBoost)
                CHECK_CLOSE (e.scorePct, std::min (100.0f, p->scorePct * 2.0f), 1e-4f);
            else
                CHECK_CLOSE (e.scorePct, p->scorePct, 1e-4f);
            CHECK (e.scorePct <= 100.0f);
        }
    }

    // Boost factor clamping: 5x behaves like 2x, 0.5x behaves like 1x.
    lib.rankAgainst (bass->dna, 1.0f, 1.0f, 1.0f, hats, 5.0f);
    const auto c5 = lib.getSnapshot();
    lib.rankAgainst (bass->dna, 1.0f, 1.0f, 1.0f, hats, 2.0f);
    const auto c2 = lib.getSnapshot();
    for (size_t i = 0; i < c5.size(); ++i)
        CHECK (c5[i].scorePct == c2[i].scorePct);

    lib.rankAgainst (bass->dna, 1.0f, 1.0f, 1.0f, hats, 0.5f);
    const auto c05 = lib.getSnapshot();
    for (const auto& e : c05)
    {
        const auto* p = findEntry (plain, e.name.toRawUTF8());
        CHECK (p != nullptr);
        if (p != nullptr)
            CHECK_CLOSE (e.scorePct, p->scorePct, 1e-4f);
    }
}

