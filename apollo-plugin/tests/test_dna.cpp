static void test_extractor_gates()
{
    BEGIN_TEST ("extractor_gates");

    DnaExtractor ex;
    DnaFingerprint out;

    // Digital silence -> no DNA.
    const auto silence = std::vector<float> ((size_t) 176400, 0.0f);
    CHECK (! ex.extractDna (silence.data(), (int) silence.size(), 44100.0, out));
    CHECK (! out.valid);

    // Below the -60 dBFS gate (rms = A/sqrt(2) < 0.001).
    const auto whisper = makeSine (440.0f, 0.001f, 44100.0, 4.0);
    CHECK (! ex.extractDna (whisper.data(), (int) whisper.size(), 44100.0, out));

    // Just above the gate.
    const auto audible = makeSine (440.0f, 0.002f, 44100.0, 4.0);
    CHECK (ex.extractDna (audible.data(), (int) audible.size(), 44100.0, out));
    CHECK (out.valid);

    // Degenerate inputs.
    const auto tone = makeSine (440.0f, 0.5f, 44100.0, 4.0);
    CHECK (! ex.extractDna (nullptr, (int) tone.size(), 44100.0, out));
    CHECK (! ex.extractDna (tone.data(), 100, 44100.0, out)); // < one FFT frame
    CHECK (! ex.extractDna (tone.data(), (int) tone.size(), 0.0, out));
}

static void test_extractor_tone_bands()
{
    BEGIN_TEST ("extractor_tone_bands");

    DnaExtractor ex;
    DnaFingerprint low, mid, high;

    CHECK (ex.extractDna (makeSine (55.0f, 0.5f, 44100.0, 4.0).data(), 176400, 44100.0, low));
    CHECK (ex.extractDna (makeSine (440.0f, 0.5f, 44100.0, 4.0).data(), 176400, 44100.0, mid));
    CHECK (ex.extractDna (makeSine (10000.0f, 0.5f, 44100.0, 4.0).data(), 176400, 44100.0, high));
    CHECK (low.valid && mid.valid && high.valid);

    std::printf ("    macro 55Hz   = [%.1f, %.1f, %.1f]\n",
                 low.macro[0], low.macro[1], low.macro[2]);
    std::printf ("    macro 440Hz  = [%.1f, %.1f, %.1f]\n",
                 mid.macro[0], mid.macro[1], mid.macro[2]);
    std::printf ("    macro 10kHz  = [%.1f, %.1f, %.1f]\n",
                 high.macro[0], high.macro[1], high.macro[2]);

    // Each pure tone dominates its macro band.
    CHECK (low.macro[0] > low.macro[1] && low.macro[0] > low.macro[2]);
    CHECK (mid.macro[1] > mid.macro[0] && mid.macro[1] > mid.macro[2]);
    CHECK (high.macro[2] > high.macro[0] && high.macro[2] > high.macro[1]);
}

static void test_extractor_determinism()
{
    BEGIN_TEST ("extractor_determinism");

    DnaExtractor ex;
    const auto buf = makeSine (440.0f, 0.5f, 44100.0, 4.0);
    DnaFingerprint a, b;
    CHECK (ex.extractDna (buf.data(), (int) buf.size(), 44100.0, a));
    CHECK (ex.extractDna (buf.data(), (int) buf.size(), 44100.0, b));

    // Same input -> bit-identical DNA (pure function; no randomness, no state).
    for (int i = 0; i < 3; ++i)
        CHECK (a.macro[i] == b.macro[i]);
    for (int i = 0; i < 16; ++i)
        CHECK (a.subBands[i] == b.subBands[i]);
}

static void test_extractor_loudness_invariance()
{
    BEGIN_TEST ("extractor_loudness_invariance");

    DnaExtractor ex;
    const auto loud  = makeSine (440.0f, 0.5f, 44100.0, 4.0);
    const auto quiet = makeSine (440.0f, 0.05f, 44100.0, 4.0); // -20 dB
    DnaFingerprint dl, dq;
    CHECK (ex.extractDna (loud.data(), (int) loud.size(), 44100.0, dl));
    CHECK (ex.extractDna (quiet.data(), (int) quiet.size(), 44100.0, dq));

    // Mean-normalized dB: a 20 dB level change must barely move the DNA,
    // because ranking compares tone, not level.
    const float sim = cosine3 (dl.macro, dq.macro);
    std::printf ("    cosine(440Hz @-6dBFS, 440Hz @-26dBFS) = %.6f\n", sim);
    CHECK (sim > 0.999f);
}

