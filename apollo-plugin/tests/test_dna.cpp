// test_dna.cpp — headless tests for Apollo v2's DNA analysis engine.
//
// Covers, with no DAW, no GUI and no audio hardware:
//   * DnaFingerprint statics (sub-band edges, macro-band mapping)
//   * DnaExtractor (silence gate, tone -> band mapping, determinism,
//     loudness invariance, the linear-power path incl. fingerprintFromLinearPower)
//   * DnaLibrary (demo-folder scan, role tags, DNA-to-DNA ranking, band
//     weights incl. the all-zero fallback, energy-role boost incl. clamping)
//   * MatchAnalyzer (live DNA capture, listen-source selection, freeze,
//     loop scan incl. the silent auto-stop disarm, band-weight clamping,
//     status/debug text, energy-section names)
//
// DnaLibrary reads ~/Music/Apollo/DemoLibrary (generated by
// tools/make_demo_library.py). The scan is strictly read-only, so the
// library doubles as documented test data (tone classes + role tags per
// tools/DEMO_LIBRARY.md). Tests that need it SKIP (counted, non-failing)
// when the folder isn't installed as documented — macOS's NSHomeDirectory()
// ignores a runtime $HOME override, so hermetic redirection is not possible.

