static void test_extractor_linear_power()
{
    BEGIN_TEST ("extractor_linear_power");

    DnaExtractor ex;
    std::array<double, 16> power {};
    double rms = -1.0;

    // Silent input: false, outputs zeroed.
    const auto silence = std::vector<float> ((size_t) 176400, 0.0f);
    CHECK (! ex.computeLinearBandPower (silence.data(), (int) silence.size(),
                                        44100.0, power, rms));
    CHECK (rms == 0.0);
    for (double p : power)
        CHECK (p == 0.0);

    // Sine: true, RMS ~= A/sqrt(2).
    const auto buf = makeSine (440.0f, 0.5f, 44100.0, 4.0);
    CHECK (ex.computeLinearBandPower (buf.data(), (int) buf.size(), 44100.0, power, rms));
    CHECK_CLOSE (rms, 0.5 / std::sqrt (2.0), 0.005);

    // The static dB tail agrees exactly with the full extractDna path.
    const DnaFingerprint viaStatic = DnaExtractor::fingerprintFromLinearPower (power);
    DnaFingerprint viaFull;
    CHECK (ex.extractDna (buf.data(), (int) buf.size(), 44100.0, viaFull));
    CHECK (viaStatic.valid);
    for (int i = 0; i < 3; ++i)
        CHECK (viaStatic.macro[i] == viaFull.macro[i]);
    for (int i = 0; i < 16; ++i)
        CHECK (viaStatic.subBands[i] == viaFull.subBands[i]);
}

