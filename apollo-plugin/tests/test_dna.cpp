static void test_fingerprint_statics()
{
    BEGIN_TEST ("fingerprint_statics");

    CHECK (DnaFingerprint::subBandEdgeHz (0) == 40.0f);
    CHECK (DnaFingerprint::subBandEdgeHz (DnaFingerprint::numSubBands) == 20000.0f);
    for (int i = 0; i < DnaFingerprint::numSubBands; ++i)
        CHECK (DnaFingerprint::subBandEdgeHz (i + 1) > DnaFingerprint::subBandEdgeHz (i));

    // Macro band edges: LOW < 250, MID 250-4000, HIGH > 4000.
    CHECK (DnaFingerprint::macroBandForHz (100.0f) == 0);
    CHECK (DnaFingerprint::macroBandForHz (249.9f) == 0);
    CHECK (DnaFingerprint::macroBandForHz (250.0f) == 1); // boundary -> mid
    CHECK (DnaFingerprint::macroBandForHz (3999.0f) == 1);
    CHECK (DnaFingerprint::macroBandForHz (4000.0f) == 2); // boundary -> high
    CHECK (DnaFingerprint::macroBandForHz (15000.0f) == 2);
}

