static void test_analyzer_scan()
{
    BEGIN_TEST ("analyzer_scan");

    MatchAnalyzer an;
    an.prepare (44100.0, 512);

    // Arm FIRST, then feed audio — the real usage order (SCAN is armed, then
    // the loop plays). Windows consumed before the arm are not accumulated.
    an.setScanBars (2);
    an.setHostTempo (120.0f, 4); // 2 bars * 4 beats @120bpm = 4.0 s
    CHECK (an.getScanBarsArmed() == 4); // arming happens on the rising edge
    an.setScanRequested (true);
    CHECK (waitFor ([&] { return an.isScanActive(); }, 2000));
    CHECK (an.getScanBarsArmed() == 2);

    // Two full analysis windows for the scan to accumulate.
    pushBlocks (an, makeSine (440.0f, 0.5f, 44100.0, 8.0), false);

    // Observe a plausible 1-based bar counter while the scan is active.
    bool sawBar = false;
    for (int i = 0; i < 25 && ! sawBar; ++i)
    {
        const int bar = an.getScanCurrentBar();
        if (bar >= 1 && bar <= 2)
            sawBar = true;
        std::this_thread::sleep_for (std::chrono::milliseconds (200));
    }
    CHECK (sawBar);

    CHECK (waitFor ([&] { return an.isScanLatched(); }, 12000));
    CHECK (! an.isScanActive());
    CHECK (an.getScanCurrentBar() == 0); // inactive -> 0

    const auto scanDna = an.getScanDna();
    CHECK (scanDna.valid);
    CHECK (scanDna.macro[1] > scanDna.macro[0]
        && scanDna.macro[1] > scanDna.macro[2]); // 440 Hz = mid
    CHECK (an.getDnaStatusText().contains ("SCANNED"));

    // H6: the time-integrated scan DNA matches a direct extraction of the
    // same stationary tone. Both windows' linear power is accumulated, so the
    // scan averages two phase realizations of the (non-bin-centered) sine —
    // it is close to, but not bit-identical with, a single direct extraction.
    DnaExtractor ex;
    DnaFingerprint direct;
    const auto first4 = makeSine (440.0f, 0.5f, 44100.0, 4.0);
    CHECK (ex.extractDna (first4.data(), (int) first4.size(), 44100.0, direct));
    const float sim = cosine3 (scanDna.macro, direct.macro);
    std::printf ("    scan   macro = [%.1f, %.1f, %.1f]\n",
                 scanDna.macro[0], scanDna.macro[1], scanDna.macro[2]);
    std::printf ("    direct macro = [%.1f, %.1f, %.1f]\n",
                 direct.macro[0], direct.macro[1], direct.macro[2]);
    std::printf ("    cosine(scan DNA, direct DNA) = %.6f\n", sim);
    CHECK (sim > 0.9f);

    // The QA hook reports exactly the two accumulated windows.
    {
        const std::string dbg = an.getDnaDebugString().toStdString();
        const auto pos = dbg.find ("captured_windows=");
        CHECK (pos != std::string::npos);
        if (pos != std::string::npos)
            CHECK (std::atoi (dbg.c_str() + pos + 17) == 2);
    }

    // Toggle off clears the latch.
    an.setScanRequested (false);
    CHECK (waitFor ([&] { return ! an.isScanLatched(); }, 2000));
    CHECK (! an.getScanDna().valid);
}

