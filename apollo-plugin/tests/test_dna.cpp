// Helpers.

static std::vector<float> makeSine (float freqHz, float amp, double sampleRate,
                                    double seconds, float phase = 0.0f)
{
    const size_t n = (size_t) (sampleRate * seconds);
    std::vector<float> out (n);
    const float inc = 2.0f * 3.141592653589793f * freqHz / (float) sampleRate;
    for (size_t i = 0; i < n; ++i)
        out[i] = amp * std::sin (phase + inc * (float) i);
    return out;
}

static float cosine3 (const std::array<float, 3>& a, const std::array<float, 3>& b)
{
    float dot = 0.0f, na = 0.0f, nb = 0.0f;
    for (int i = 0; i < 3; ++i)
    {
        dot += a[i] * b[i];
        na  += a[i] * a[i];
        nb  += b[i] * b[i];
    }
    if (na <= 1e-12f || nb <= 1e-12f)
        return 0.0f;
    return dot / std::sqrt (na * nb);
}

static void pushBlocks (MatchAnalyzer& an, const std::vector<float>& mono, bool toMaster)
{
    const int bs = 512;
    std::vector<float> blk ((size_t) bs);
    for (size_t i = 0; i < mono.size(); i += (size_t) bs)
    {
        const int n = (int) std::min<size_t> ((size_t) bs, mono.size() - i);
        std::copy (mono.begin() + (std::ptrdiff_t) i,
                   mono.begin() + (std::ptrdiff_t) (i + (size_t) n), blk.begin());
        if (toMaster)
            an.pushMasterBlock (blk.data(), blk.data(), n);
        else
            an.pushSampleBlock (blk.data(), blk.data(), n);
    }
}

// The demo library as documented in tools/DEMO_LIBRARY.md: 9 WAVs + roles.txt.
static bool demoLibraryAvailable()
{
    const auto folder = DnaLibrary::getDemoFolder();
    if (! folder.isDirectory())
        return false;
    juce::Array<juce::File> wavs;
    folder.findChildFiles (wavs, juce::File::findFiles, false, "*.wav");
    return wavs.size() == 9 && folder.getChildFile ("roles.txt").existsAsFile();
}

#define SKIP_IF_NO_DEMO() \
    do { \
        if (! demoLibraryAvailable()) \
        { \
            ++g_skip; \
            std::printf ("  SKIP [%s]: ~/Music/Apollo/DemoLibrary not installed\n", g_test); \
            return; \
        } \
    } while (0)

static const DnaLibrary::RankedEntry* findEntry (
    const std::vector<DnaLibrary::RankedEntry>& snap, const char* name)
{
    for (const auto& e : snap)
        if (e.name == juce::String (name))
            return &e;
    return nullptr;
}

static const DnaLibrary::DebugEntry* findDebug (
    const std::vector<DnaLibrary::DebugEntry>& dbg, const char* name)
{
    for (const auto& e : dbg)
        if (e.name == juce::String (name))
            return &e;
    return nullptr;
}

// Read-only scan used by analyzer tests to know the expected library size.
static int scanLibrarySize()
{
    DnaExtractor ex;
    DnaLibrary lib;
    lib.scanAndAnalyze (ex);
    return lib.size();
}

