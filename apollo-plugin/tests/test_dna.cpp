// Mini test framework (no external deps).

static int g_pass = 0;
static int g_fail = 0;
static int g_skip = 0;
static const char* g_test = "";

static void checkImpl (bool cond, const char* expr, const char* file, int line)
{
    if (cond)
    {
        ++g_pass;
    }
    else
    {
        ++g_fail;
        std::printf ("  FAIL [%s] %s:%d: %s\n", g_test, file, line, expr);
    }
}
#define CHECK(c) checkImpl ((c), #c, __FILE__, __LINE__)
#define CHECK_CLOSE(a, b, eps) checkImpl (std::fabs ((double) (a) - (double) (b)) <= (eps), \
                                          #a " ~= " #b, __FILE__, __LINE__)

#define BEGIN_TEST(name) do { g_test = name; std::printf ("- %s\n", name); } while (0)

template <typename F>
static bool waitFor (F&& cond, int timeoutMs, int pollMs = 50)
{
    const auto start = std::chrono::steady_clock::now();
    for (;;)
    {
        if (cond())
            return true;
        const auto elapsed = std::chrono::duration_cast<std::chrono::milliseconds> (
            std::chrono::steady_clock::now() - start).count();
        if (elapsed >= timeoutMs)
            return cond();
        std::this_thread::sleep_for (std::chrono::milliseconds (pollMs));
    }
}

